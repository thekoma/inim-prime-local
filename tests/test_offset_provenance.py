"""The committed firmware offset map must match the code (anti-drift guard).

Every EEPROM address in ``_LAYOUTS`` is tied back to its DLL-attested value and
provenance recorded under ``tools/offsets/data`` (regenerated by
``tools/offsets/extract_offsets.py``), so a constant cannot silently drift from
the firmware it was recovered from. See ``tools/offsets/README.md``.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from custom_components.inim_prime.client import local6004 as m

_OFFSETS = json.loads(
    (Path(__file__).resolve().parents[1] / "tools/offsets/data/centrale5.offsets.json").read_text()
)

# Major digit used by _LAYOUTS -> firmware version key in the extractor JSON.
_MAJOR_TO_FW = {"4": "4.00", "5": "5.00"}

# _Layout address fields the extractor recovers, each named like the JSON field.
_ADDR_FIELDS = (
    "zone_cfg",
    "terminal_cfg",
    "pulse_cfg",
    "zone_opt2",
    "scenario_modi",
    "area_labels",
    "zone_labels",
    "scenario_labels",
    "output_labels",
    "log_addr",
)
_CONFIG_FIELDS = (
    "zone_cfg",
    "terminal_cfg",
    "pulse_cfg",
    "zone_opt2",
    "scenario_modi",
    "area_labels",
    "zone_labels",
    "scenario_labels",
    "output_labels",
)
_PROVENANCE_KEYS = ("symbol", "source", "method", "file_offset", "il_bytes")


def _fields(major: str) -> dict:
    return _OFFSETS["firmwares"][_MAJOR_TO_FW[major]]["fields"]


def test_every_layout_has_a_firmware_map() -> None:
    """A new _LAYOUT must be added to _MAJOR_TO_FW so this suite guards it too."""
    assert set(m._LAYOUTS) == set(_MAJOR_TO_FW)


@pytest.mark.parametrize("major", sorted(_MAJOR_TO_FW))
def test_layout_addresses_match_dll(major: str) -> None:
    """Each mapped offset equals its DLL-attested address (None = intentional gap)."""
    layout = m._LAYOUTS[major]
    fields = _fields(major)
    for name in _ADDR_FIELDS:
        coded = getattr(layout, name)
        if coded is None:
            # a table the DLL attests but the code deliberately leaves unmapped
            # until it is verified on live hardware.
            continue
        assert name in fields, f"{name} is mapped in code but absent from the DLL map"
        assert coded == int(fields[name]["addr"], 16), f"{major}: {name} drifted from the DLL"


@pytest.mark.parametrize("major", sorted(_MAJOR_TO_FW))
def test_record_counts_match_dll(major: str) -> None:
    """DLL-derived counts agree with the layout's half-offset and scenario count."""
    fields = _fields(major)
    layout = m._LAYOUTS[major]
    assert fields["zone_cfg"]["record_size"] == m._ZONE_CFG_REC
    assert fields["zone_cfg"]["count"] == 2 * layout.half_offset
    assert fields["terminal_cfg"]["record_size"] == m._TERMINAL_CFG_REC
    assert fields["terminal_cfg"]["count"] == layout.half_offset
    assert fields["pulse_cfg"]["record_size"] == m._PULSE_CFG_REC
    assert fields["pulse_cfg"]["count"] == layout.terminal_count
    assert fields["zone_opt2"]["count"] == 2 * layout.half_offset
    assert fields["scenario_modi"]["record_size"] == m._SCENARIO_MODI_REC
    assert fields["scenario_modi"]["count"] == m._SCENARIO_COUNT


@pytest.mark.parametrize("major", sorted(_MAJOR_TO_FW))
def test_provenance_is_complete_and_self_consistent(major: str) -> None:
    """Every recovered field names its origin, and il_bytes re-derives the addr."""
    for name, field in _fields(major).items():
        for key in _PROVENANCE_KEYS:
            assert field.get(key), f"{major}: {name} missing provenance '{key}'"
        # il_bytes is the raw `ldc.i4 <addr>` immediate (0x20 + LE32).
        raw = bytes(int(b, 16) for b in field["il_bytes"].split())
        assert raw[0] == 0x20 and len(raw) == 5, f"{major}: {name} unexpected il_bytes"
        assert int.from_bytes(raw[1:], "little") == int(field["addr"], 16)


@pytest.mark.parametrize("major", sorted(_MAJOR_TO_FW))
def test_context_op_matches_reader_region(major: str) -> None:
    """Config fields are read via _OPEN_CFG (0x17), the event log via _OPEN_LOG (0x1f).

    This guards against a mis-regioned field; it is a region-classification check,
    not an independent decode of the panel's read opcode.
    """
    fields = _fields(major)
    for name in _CONFIG_FIELDS:
        assert int(fields[name]["context_op"], 16) == m._OPEN_CFG[0]
    assert int(fields["log_addr"]["context_op"], 16) == m._OPEN_LOG[0]
